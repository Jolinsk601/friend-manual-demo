# ============================================================
# V1.5：自动补 social_x / social_y（二维坐标图用）
# 规则：
#   social_x = 表达方式（内向观察 ← → 主动表达），范围 [-50, +50]
#   social_y = 关系节奏（快速连接 ↑ / 慢慢深入 ↓），范围 [-50, +50]
# 不是真实算法，是按 params 拍的位置，供 V1.5 二维图视觉使用
# ============================================================
def _derive_social_coord(params: dict) -> dict:
    token = params.get("token", "")
    firewall = params.get("firewall", "")

    # X 轴：表达方式（越主动 +50，越内向 -50）
    x_map = {
        "快速输出型": 35, "混合型": 0, "结构化输出型": 15, "稳态输出型": 10,
        "思考后输出型": -25, "深度输出型": -30, "异步输出型": -20, "体验型输出": 20,
    }
    x = x_map.get(token, 0)

    # Y 轴：关系节奏（快速连接 +50，慢慢深入 -50）
    y_map = {
        "快速开放": 40, "高度开放": 35, "场景变化": 15, "中等开放": 0,
        "慢热开放": -25, "慢热开放（线上）": -15, "高度选择": -40,
    }
    y = y_map.get(firewall, 0)
    return {"social_x": x, "social_y": y}


